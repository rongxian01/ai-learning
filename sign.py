# sign.py —— 第 12 项验收：你自己写一个 if / elif / else
#
# 任务：让用户输入一个整数，判断它是"正数""负数"还是"零"。
#
# 要求（四条都要做到）：
#   1. 用 input() 收数，记得 int() 转成数字才能比大小
#   2. if / elif / else 三条路全用上，一条不许落
#   3. else 那路专门留给"零"——提示：不是 >0 也不是 <0，剩下的就是 0
#   4. 冒号 + 缩进圈地盘；每写一行，行尾加一句人话注释"这行干嘛"
#
# 自测三个数：7（→正数） / -3（→负数） / 0（→零）
# 写完跑：python sign.py
#
# ==================== 在下面写你的代码 ====================

num = int(input("请输入一个数字"))    # input 收回是文本，int() 转成数字才能比大小
if num > 0:                          # 问：这个数比 0 大吗？
    print("正数")                    # 是 → 正数
elif num < 0:                        # 上一个没中，再问：比 0 小吗？
    print("负数")                    # 是 → 负数
else:                                # 两个都没中——剩下的正好是 0
    print("零")                      # 兜底 → 零