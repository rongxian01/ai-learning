# ============================================================
# comp_sources.py —— 推导式「队伍」大全
#
# for x in <队伍>，in 后面能接什么？
# 总纲一句：队伍 = 排成一队的东西，能逐个摘就能当队伍
# 每种队伍真正要问的是：摘出来的那个人，是谁？
#
# 跑通标准：8 行输出，每行看清「摘出来的是什么」
# ============================================================


# ---------- 1. 列表（最常见，摘出来 = 元素）----------
nums = [1, 2, 3]
print("1 列表：", [x * 10 for x in nums])
# 摘出来：1、2、3（元素本身）

# ---------- 2. 字符串（逐个字符！词频课 for ch in word 那个）----------
word = "螺栓"
print("2 字符串：", [ch for ch in word])
# 摘出来：'螺'、'栓'（一个字符就是一个人，不是整个词）

# ---------- 3. 字典直接上（⚠️ 只给键！这是最大的坑）----------
scores = {"数学": 90, "英语": 85}
print("3 字典直接：", [k for k in scores])
print("3 字典keys：", [k for k in scores.keys()])
# 两行一样！字典不喊 .keys() 也只给键：'数学'、'英语'

# ---------- 4. 字典 .values()（要值必须喊）----------
print("4 values：", [v for v in scores.values()])
# 摘出来：90、85（分数）

# ---------- 5. 字典 .items()（要成对，左边必须两个变量）----------
print("5 items字典：", {k: v for k, v in scores.items()})
print("5 items拼句：", [f"{k}考了{v}分" for k, v in scores.items()])
# 摘出来：('数学', 90)、('英语', 85)——一对，左边 k, v 拆开接

# ---------- 6. 集合（无序，别核顺序）----------
materials = {"M8", "M10", "M6"}
print("6 集合：", [m for m in materials])
# 摘出来：三种规格，但顺序每次跑可能不一样

# ---------- 7. 元组（同列表，有序有号）----------
spec = (10, 20, 30)
print("7 元组：", [x + 1 for x in spec])
# 摘出来：10、20、30

# ---------- 8. range（数字队伍）----------
print("8 range：", [i * i for i in range(1, 6)])
# 摘出来：1、2、3、4、5（i 自己会走位，不用你建列表）

# ============================================================
# 收束：一张表记住
#   列表/元组  → 摘出元素        字符串 → 摘出单个字符
#   字典       → 摘出键（默认！）  字典.values() → 摘出值
#   字典.items() → 摘出键值对（左边两个变量）  集合 → 摘出元素（无序）
#   range     → 摘出数字
# 判断法：这东西能逐个摘吗？能，就能当队伍。
# ============================================================
