# loop.py —— for 循环：对"一堆东西"逐个干活
#
# 以前的程序一次处理一个值；有了 for，能一次处理"一批"。
# 读法：for 每个元素 in 一堆东西:  逐个干活
# 就像一摞图纸，你一张张过——for 就是"一张张"。

# ============ 遍历列表 ============
tasks = ["画图", "建模型", "渲图"]        # 一批任务
for task in tasks:                        # task 轮流变成"画图"→"建模型"→"渲图"
    print("做：" + task)                  # 每个都执行一遍这行

# ============ 遍历字符串（逐字）============
for ch in "设计":                         # ch 轮流变成"设"→"计"
    print(ch)

# ============ range()：要一串数字时 ============
for i in range(5):                        # i 轮流变成 0,1,2,3,4（共 5 个，但不含 5）
    print("第" + str(i) + "次")
