# tuple.py —— 第 23 项 元组概念课
# 规则同前：从头跑到尾，看每幕的输出；看完再开 tuplequiz.py 自己写
# 类比：元组 = 规格书（定稿不能涂改），列表 = 草稿本（随时能改）

# ── 第 1 幕：长什么样 ──
# 列表用方括号，元组用圆括号——就这一个符号的差别
tools_list = ["扳手", "螺丝刀"]       # 列表：方括号
tools_tuple = ("扳手", "螺丝刀")      # 元组：圆括号
print(tools_list)
print(tools_tuple)

# ⚠️ 单元素的坑：一个元素的元组，逗号不能省！
one = (1)            # 这不是元组，是普普通通的整数 1
print(type(one))     # <class 'int'>
one_real = (1,)      # 这才是元组（就一个元素，逗号是它的身份证）
print(type(one_real))  # <class 'tuple'>
empty = ()           # 空元组，直接一对圆括号
print(type(empty))   # <class 'tuple'>

# ── 第 2 幕：索引、切片、遍历——和列表一模一样 ──
# （复习 item 19：切片不认列表，认"排成一队的东西"——元组也排成一队）
nums = (10, 20, 30, 40)
print(nums[0])       # 10    从 0 开始数，和列表同款
print(nums[-1])      # 40    最后一个
print(nums[1:3])     # (20, 30)   切片照切，含头不含尾
print(len(nums))     # 4     有几个
print(20 in nums)    # True  在不在
for n in nums:
    print(n)         # 遍历照转

# ── 第 3 幕：唯一的硬区别——不能改 ──
spec = ("M6", "螺栓", "镀锌")
print(spec[0])       # M6 ← 取，照样能取（不能改≠不能读）

# 对比：列表是草稿本，随时能改
bom = ["M6", "螺栓", "镀锌"]
bom[0] = "M8"
print(bom)           # ['M8', '螺栓', '镀锌']

# ── 第 4 幕：拆包（字典 items() 吐出的就是元组盒子）──
point = (3, 4)
x, y = point         # 一个盒子拆两件，左边两个变量
print(x, y)          # 3 4

scores = {"语文": 92, "数学": 88}
for k, v in scores.items():
    # items() 每轮吐出一个 ('语文', 92) 这样的小元组，k, v 把它拆开
    print(k, v)

# ── 第 5 幕：元组能当字典的键，列表不能 ──
# （复习 item 20：键必须"不会变"——元组不会变，所以它能当键）
locations = {
    (0, 0): "家",
    (1, 2): "公司",
}
print(locations[(0, 0)])    # 家——坐标当地名，一行查得到

# locations[[0, 0]] = "家"  # ← 列表当键，直接炸：
# TypeError: unhashable type: 'list'

# ── 第 6 幕：什么时候必须用元组 ──
# ① 数据定稿了不想被手滑改掉（规格书、坐标、配置常量）
# ② 要当字典的键（坐标→地名、组合键→值）
# ③ 函数一次返回多个值（模块 D 会学 return a, b）
# 一句话：**"不想被改"和"要当键"用元组；"还要加新删旧"用列表**

# ── 第 7 幕：元组只有两个方法 ──
# 列表那堆 append/insert/pop/remove 元组一个都没有（不能改，加什么删什么）
t = ("a", "b", "a", "c")
print(t.count("a"))    # 2   数"a"出现几回
print(t.index("b"))    # 1   "b"在几号位

# ── 附：互相转换 ──
print(tuple([1, 2, 3]))    # (1, 2, 3)   列表 → 元组
print(list((1, 2, 3)))     # [1, 2, 3]   元组 → 列表

