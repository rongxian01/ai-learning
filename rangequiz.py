# 题 1：热身 · 三个参数的位置
# 用 range(0, 20, 3) 打印所有被 3 整除的数，一行一个
# 提示：三个参数分别管"从哪开始 / 到哪停 / 每次跳多少"
# —— 在下面写 ——
for i in range(0, 20, 3):
    if i % 3 == 0:
        print(i)

        
    


# 题 2：倒着数
# 从 20 倒数到 1（含 20 含 1），一行一个
# 提示：步长给负数；stop 要写 0 才能带上 1
# —— 在下面写 ——
for x in range(20, 0, -1):
    print(x)

# 题 3：老坑重验 · 1 到 10 的偶数
# 打印 2 4 6 8 10（含 10），一行一个
# 提示：步长 2；⚠️ 含头不含尾在这里会咬人——想带 10，stop 该写几？
# —— 在下面写 ——
for y in range(2, 11, 2):
    print(y)

# 题 4（验收题）：倒着数偶数
# 从 20 开始，每次倒 2，到 2 结束（输出 20 18 16 ... 4 2，不含 0），一行一个
# 提示三件套：① 起点大数 ② 步长负 2 ③ stop 要让 2 出得来
# —— 在下面写 ——

