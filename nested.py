# nested.py —— 第 16 项 嵌套循环 概念课
# 核心一句话：外层转 1 圈，内层转 1 整圈

# ========== 第 1 幕：最小例子——看清"圈套圈"怎么转 ==========
print("=== 第 1 幕：外层 2 圈 × 内层 3 圈 ===")
for i in range(2):          # 外层：i = 0, 1
    for j in range(3):      # 内层：每轮到一次 i，j 都从 0 数到 2
        print(f"外层{i} 内层{j}")

# 数一下输出：2 × 3 = 6 行
# 看清顺序：外层0(内层0/1/2) → 外层1(内层0/1/2)
# 外层是"慢针"，内层是"快针"——内层跑完一整轮，外层才走一步

# ========== 第 2 幕：热身——内层不循环，用字符串复制 ==========
print("=== 第 2 幕：三角星号 ===")
for i in range(1, 6):
    print("*" * i)          # "*" * 1 = *，* 2 = **，* 3 = ***...

# ========== 第 3 幕：九九乘法表（本项终极目标） ==========
print("=== 第 3 幕：九九乘法表 ===")
for i in range(1, 10):           # 外层：行号 1-9
    for j in range(1, i + 1):    # 内层：列号 1-i（第 i 行只有 i 列）★注意 i+1：含头不含尾
        print(f"{j}×{i}={i * j}", end="  ")   # end="  " = 不换行，隔两空格
    print()                      # 内层转完了，这才换行（注意它缩进在外层体里，不在内层体里！）

# 走一遍流程你就懂了：
# i=1 → 内层 j=1 → 打"1×1=1" → 内层结束 → print() 换行
# i=2 → 内层 j=1,2 → 打"1×2=2  2×2=4" → 换行
# ...
# i=9 → 内层 j=1..9 → 打完一整行 → 换行

# ⚠️ 三个翻车点（做题时盯死）：
# 1. range(1, i+1) 的 +1——含头不含尾，要 1到i 就得 i+1（老坑第 N 次）
# 2. end="  " 忘写 → 每格都换行，不成表
# 3. print() 换行那行的缩进——在外层体里（4格），缩进到内层体里（8格）= 每格都换行
