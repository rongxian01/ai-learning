# operators.py —— 除法三兄弟 + 取模实战

# / 真除法：结果永远是小数（float），整除也带 .0
print(7 / 2)              # 3.5
print(6 / 2)              # 3.0

# // 整除（地板除）：往下取整，结果是整数（int）
print(7 // 2)             # 3
print(135 // 60)          # 2 —— 135 秒里有几个整分钟

# % 取模：除完剩多少零头
print(7 % 2)              # 1
print(135 % 60)           # 15 —— 除完整分钟后剩几秒

# 实战 1：奇偶判断（隔行变色、斑马纹的代码根基）
print(5 % 2 == 0)         # False → 奇数
print(6 % 2 == 0)         # True → 偶数

# 实战 2：取模的循环性
print(0 % 3, 1 % 3, 2 % 3, 3 % 3, 4 % 3)   # 0 1 2 0 1 —— 到 3 就归零重来

# 实战 3：秒 → 分:秒（// 和 % 的经典配合）
total = 135
print(f"{total // 60}分{total % 60}秒")     # 2分15秒
