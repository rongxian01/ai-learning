# ============================================================
# 第三幕：字典推导  {t: len(t) for t in tools}
#   人话：tools 里每个工具，量一下名字几个字，登记成「工具: 字数」
# ============================================================

tools = ["螺栓", "螺母", "垫片", "卡扣"]

# --- 循环版 ---
lengths_loop = {}
for t in tools:
    lengths_loop[t] = len(t)

# --- 推导版 ---
lengths_comp = {t: len(t) for t in tools}

print("第三幕 循环版：", lengths_loop)
print("第三幕 推导版：", lengths_comp)
print("第三幕 一样吗：", lengths_loop == lengths_comp)

# 拆解（对照 lengths_loop[t] = len(t) 看）：
#   t : len(t)   ← 冒号左边 = 键（就是循环里方括号里那位 t）
#                  冒号右边 = 值（就是循环里等号右边那位 len(t)）
#   冒号 = 赋值行的压缩：d[k] = v 压成 k: v
#   花括号 = 告诉 Python「我要一个字典」

# 动手1：tools 里加一个 "开口销"，看字典多一对
# 动手2：len(t) 改成 len(t) * 10，值那边随你加工


# ============================================================
# 收束：三种写法一个模子
#   [生产什么 for 变量 in 队伍]          → 列表
#   [生产什么 for 变量 in 队伍 if 盘问]   → 列表（带门卫）
#   {键: 值 for 变量 in 队伍}            → 字典
# 读法铁律：从 for 读起。for 之前是「要什么」，for 之后是「从哪来、怎么盘」
