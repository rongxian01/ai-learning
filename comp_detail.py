# ============================================================
# 第一幕：列表推导  [x * x for x in nums]
#   人话：nums 里每个数，平方一遍，收集成新列表
# ============================================================

nums = [1, 2, 3, 4, 5]

# --- 循环版（老办法，三步）---
squares_loop = []
for x in nums:
    squares_loop.append(x * x)

# --- 推导版（新办法，一步）---
squares_comp = [x * x for x in nums]

print("第一幕 循环版：", squares_loop)
print("第一幕 推导版：", squares_comp)
print("第一幕 一样吗：", squares_loop == squares_comp)

# 拆解（对照循环版看）：
#   x * x        ← 每轮生产的东西（循环里 append( 那位就是它）
#   for x in nums ← 从 nums 逐个摘，每轮装进 x（for 是 x 的唯一生产者）
#   [ ... ]      ← 方括号 = 告诉 Python「我要一个列表」

# 动手1：把 nums 改成 [2, 4, 6]，先猜输出，再跑，对答案
# 动手2：把 x * x 改成 x * 10，再跑——「生产的东西」由你定


# ============================================================
# 第二幕：if 过滤  [x for x in nums if x > 0]
#   人话：nums 里每个数，盘问一遍「你 > 0 吗」，过关的才收
# ============================================================

nums2 = [3, -1, 5, -7, 2, 0, 8]

# --- 循环版 ---
positives_loop = []
for x in nums2:
    if x > 0:
        positives_loop.append(x)

# --- 推导版 ---
positives_comp = [x for x in nums2 if x > 0]

print("第二幕 循环版：", positives_loop)
print("第二幕 推导版：", positives_comp)
print("第二幕 一样吗：", positives_loop == positives_comp)

# 拆解：
#   和第一幕比只多一截 if x > 0 —— 它站末尾当门卫
#   流程：for 摘一个来 → if 盘问 → 过关才收进方括号
#   位置铁律：for 打头，if 垫后。if 站前面直接 SyntaxError
