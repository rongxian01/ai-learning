# branch.py —— 程序第一次会"看情况分岔"：if / elif / else
# 以前的程序只会"照着念"（从上到下执行）；有了 if，程序会拐弯。
#
# 读代码前先懂三句话：
#   if 条件:      —— 如果条件成立，就做缩进里那段
#   elif 条件:    —— 否则如果另一个条件成立，做缩进里那段（elif = else if）
#   else:         —— 上面全不中，做缩进里那段（兜底）
# Python 不用大括号 {} 圈地盘，靠"冒号 + 缩进"认谁是谁的地盘。

# ============ 第一部分：if 问的问题（比较运算符）============
# 一个 = 是"赋值"（贴标签），两个 == 才是问"两边等不等"
print(5 == 5)      # True  —— 5 等于 5 吗？成立
print(5 > 3)       # True  —— 5 大于 3 吗？成立
print(5 < 3)       # False —— 5 小于 3 吗？不成立
print(5 != 3)      # True  —— 5 不等于 3 吗？成立（!= 就是"不等"）
# 这些问题的答案只有两种：True（真）/ False（假），叫 bool 类型

# ============ 第二部分：if / elif / else 分岔 ============
score = int(input("你考了几分？"))     # input 收回的是文本，int() 转成数字才能比大小

if score >= 90:
    print("优秀")          # 这行缩进了，属于 if 的地盘：>=90 才执行
elif score >= 60:
    print("及格")          # 上一个没中，才轮到这个判断：>=60 执行
else:
    print("挂科")          # 上面全不中，兜底走这里

# 读法：>=90 → 优秀；不然 >=60 → 及格；都不行 → 挂科
# 注意顺序：从上往下挨着问，谁先命中谁说了算，后面不再看
